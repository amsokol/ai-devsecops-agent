"""Answering "how do I fix this?" with the change itself, prepared where it can be checked.

The same session as a maintenance fix, aimed at a person instead of at a branch. A fix task edits an
isolated copy of the repository and the overlay's verification runs there, so what comes back is a
change somebody tried rather than a change somebody wrote out. Nothing is committed and nothing is
pushed: the diff is read out of that copy, offered in the conversation, and the copy is thrown away.

Two things are deliberately not the model's:

*The change that is shown.* It is `git diff` of the copy, never the session's own account of what it
did. A patch quoted from prose is a patch nobody verified, and it is the one that would be applied.

*The label under it.* "Verified" is matched against the commands the session actually ran, exactly
as it is for a branch. A patch that could not be shown safe is still offered — the question was how
to fix it — but it says so, because a person clicking "commit suggestion" is trusting that label.

What the session does supply is the paragraph above the change: why the edit is what it is. It is
written by whoever made the edit, in the same session and from the same context, so the words and
the diff cannot drift apart.
"""

from __future__ import annotations

import asyncio
import hashlib
import re
from dataclasses import dataclass
from pathlib import Path

from agent.answer import REPLY_LIMIT, Answered
from agent.backends.port import Budget, Failure
from agent.backends.select import Roster
from agent.brief import FIX_RESULT_SHAPE, compose, knowledge_for, quoted, role_instructions
from agent.budget import Ledger
from agent.containment import Checkout
from agent.domain import AnswerOutcome, FixOutcome, PlannedTask, Reason, Role
from agent.errors import ConfigError
from agent.executor import run_attempts
from agent.findings import slug
from agent.library import Library
from agent.remediate import VERIFICATION_POLICY, already_broken
from agent.repo import Repository, Worktree
from agent.results import FixResult, read_fix_result
